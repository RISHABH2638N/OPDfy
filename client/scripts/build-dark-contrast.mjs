// Mechanical, colour-only companion to the legacy stylesheets. No layout,
// visibility, event handling, user content or print declarations are rewritten.
import fs from 'node:fs';
import postcss from 'postcss';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['styles.css', 'theme-premium.css', 'queue-intervention-fix.css', 'department-referrals.css'];
const luminance = rgb => rgb.map(c => c / 255).map(c => c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4).reduce((v,c,i) => v+c*[.2126,.7152,.0722][i],0);
function remap(token, ink) {
  let rgb, alpha = 1;
  if (/^#/.test(token)) {
    let hex = token.slice(1);
    if (hex.length <= 4) hex = [...hex].map(c => c+c).join('');
    rgb = [0,2,4].map(i => parseInt(hex.slice(i,i+2),16));
    if (hex.length === 8) alpha = parseInt(hex.slice(6),16)/255;
  } else if (/^rgba?\(/i.test(token)) {
    const parts = token.match(/[\d.]+/g).map(Number);
    rgb = parts.slice(0,3); alpha = parts[3] ?? 1;
  } else rgb = token.toLowerCase() === 'white' ? [255,255,255] : [0,0,0];
  if (ink) {
    // Retain semantic hue, but lift dark text above 7:1 on our usual panels.
    while (luminance(rgb) < .60) rgb = rgb.map(c => c+(255-c)*.08);
    if (alpha > 0) alpha = 1;
  } else {
    if (luminance(rgb) > .45) rgb = rgb.map((c,i) => [15,34,48][i] + (c-230)*.10);
    while (luminance(rgb) > .085) rgb = rgb.map(c => c*.90);
  }
  return `rgba(${rgb.map(c => Math.round(Math.max(0,c))).join(',')},${Number(alpha.toFixed(3))})`;
}
const colour = /#[\da-f]{8}\b|#[\da-f]{6}\b|#[\da-f]{4}\b|#[\da-f]{3}\b|rgba?\(\s*[\d.]+\s*,\s*[\d.]+\s*,\s*[\d.]+(?:\s*,\s*[\d.]+)?\s*\)|\b(?:white|black)\b/gi;
const out = postcss.root();
for (const file of sources) {
  const tree = postcss.parse(fs.readFileSync(path.join(root,'src',file),'utf8'));
  tree.walkRules(rule => {
    if (rule.selector.includes('data-theme')) return;
    const parents = []; let p = rule.parent;
    while (p && p.type !== 'root') { parents.unshift(p); p=p.parent; }
    if (parents.some(p => p.type !== 'atrule' || !['media','supports'].includes(p.name) || /print/.test(p.params))) return;
    const declarations = [];
    rule.nodes.forEach(d => {
      if (d.type !== 'decl' || !['color','background','background-color','background-image','-webkit-text-fill-color','caret-color'].includes(d.prop)) return;
      const ink = /color$/.test(d.prop) && d.prop !== 'background-color';
      let value = d.value;
      // Brand colours remain unchanged in saved clinic settings. Only their
      // screen presentation is normalized for readable text/button pairs.
      value = value.replace(/var\(--(?:clinic|lounge)-(?:primary|accent)(?:,[^)]*)?\)/g, ink ? '#73dce2' : '#12606b');
      if (!ink) value = value.replace(/var\(--primary(?:-hover)?\)/g, '#12606b');
      if (!ink) value = value.replace(/var\(--(?:text|navy)\)/g, '#12606b');
      if (ink) value = value.replace(/var\(--(?:bg|surface)\)/g, '#e5eff3');
      if (!/url\(/i.test(value)) value = value.replace(colour, token => remap(token, ink));
      // Also retain resets and variable declarations so a later transparent/
      // none/variable rule still wins over an earlier literal colour rule.
      declarations.push(postcss.decl({prop:d.prop,value,important:true}));
    });
    if (!declarations.length) return;
    const selectors = rule.selectors.map(s => {
      if (/^(?:html|:root)(?=[\s.:#\[]|$)/.test(s)) return s.replace(/^(?:html|:root)/, 'html[data-theme="dark"]');
      return `html[data-theme="dark"] ${s}`;
    });
    let target = out;
    for (const parent of parents) { const at = postcss.atRule({name:parent.name,params:parent.params}); target.append(at); target=at; }
    const copy = postcss.rule({selector:selectors.join(', ')}); copy.append(declarations); target.append(copy);
  });
}
const screen = postcss.atRule({name:'media',params:'screen'}); screen.append(out.nodes);
const generated = '/* Generated by scripts/build-dark-contrast.mjs. Regenerate after adding legacy colours. */\n' + screen.toString();
fs.writeFileSync(path.join(root,'src/dark-contrast.css'), generated+'\n'+fs.readFileSync(path.join(root,'src/appearance-controls.css'),'utf8'));
console.log('Generated screen-only dark contrast rules.');
